/**
 * 获取指定等级的单字列表
 */
export function getCharList(level: Level): string[] {
	return SRC_CHAR_LIB[level] || [];
}

/**
 * 获取指定等级的词汇列表
 */
export function getWordList(level: Level): string[] {
	return SRC_WORD_LIB[level] || [];
}

/**
 * 获取指定等级的人教版单字列表
 */
export function getRJBCharList(level: RJBLevel): string[] {
	return RJB_CHAR_LIB[level] || [];
}

/**
 * 获取 SRC 等级对应的人教版等级
 */
export function getCorrespondingRJBLevel(srcLevel: Level): RJBLevel {
	const map: Record<Level, RJBLevel> = {
		SRC100: 'RJB100',
		SRC300: 'RJB300',
		SRC500: 'RJB500',
		SRC800: 'RJB800',
	};
	return map[srcLevel] ?? 'RJB100';
}
